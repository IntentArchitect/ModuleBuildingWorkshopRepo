# Custom Dispatcher Command Handler

Commands are modelled in the Services designer and generated by WorkshopModule. A request flows `Controller → IDispatcher.Send → <Command>LoggingDecorator (if any) → <Command>Handler.Handle`. There is no MediatR in this app: no `IRequestHandler`, `IPipelineBehavior`, `IMediator` or `ISender`. Don't add it.

## Commands in this application

## Business logic goes only in `Handle`

- Write it in the body of `Handle` and nowhere else. The controller, command class, logging decorator, `Dispatcher` and `DependencyInjection.cs` are all generated.
- Keep `[IntentManaged(Mode.Fully, Body = Mode.Ignore)]` on `Handle`, and keep its signature. That attribute is the only thing protecting your code. The rest of the class is fully managed.
- Replace the whole generated body: the `throw new NotImplementedException(...)` and, where present, the `// IntentInitialGen` and `// TODO` lines.
- A command with no response type returns `Unit.Value`.
- Nothing commits for you, because the dispatcher has no unit-of-work step. After changing state, `Handle` must call `SaveChangesAsync(cancellationToken)` on `IUnitOfWork` or on the repository's `UnitOfWork`. This overrides any other skill that says to omit `SaveChangesAsync` and assume an outer commit.
- For a missing entity, throw the Domain `NotFoundException`; `ExceptionFilter` turns it into a 404.

## Dependencies: Domain abstractions only

Inject only interfaces from the Domain project: entity repositories (`I<Entity>Repository`), `IUnitOfWork` and domain services. Never inject:

- `ApplicationDbContext`, `DbContext` or any other type from the Infrastructure project
- `ILogger<T>` (see below)
- `IDispatcher`, because handlers don't dispatch other commands
- Application-layer services such as `ICorrelationContext` or `ICurrentUserService`, or `IServiceProvider`, `IConfiguration`, `HttpClient` or FluentValidation validators

When the entity or repository you need is missing, model the entity in the Domain designer so that its repository is generated. Don't hand-write either one, and don't fall back to the DbContext.

The generated constructor is empty and fully managed, so a parameter or field you add by hand is deleted on the next Software Factory run. When you inject something, mark the constructor `[IntentManaged(Mode.Merge)]` and each field you add `[IntentIgnore]`. Mark any private helper method `[IntentIgnore]` too.

## Cross-cutting concerns come from the architecture

Logging is added with the **Serilog Logging** stereotype. Apply it to the command in the Services designer, choose its flags (`Log Request`, `Log Response`, `Log Duration`) and run the Software Factory. That generates `<Command>LoggingDecorator`, which is registered with Scrutor's `services.Decorate<…>` after the handler. The decorator logs the request, the response and the duration inside try/finally. Every log line already carries `CorrelationId` from the request's logging scope.

So in a handler, never:

- inject `ILogger`, time anything with a `Stopwatch`, or log "handling" or "handled" messages, the request or the response;
- write a decorator or wrapper handler by hand, or add `Decorate`/`AddScoped` lines to `DependencyInjection.cs`;
- add a try/catch only to log and rethrow.

If a command needs logging and doesn't have it, apply the stereotype; don't change the handler. Some cross-cutting concerns have no stereotype yet, such as running validators, retries, caching and authorization. Tell the user that adding one is a module change, and don't build it into the handler.
""")
                .OnBuild(file =>
                {
                    var unitNamespace = (ExecutionContext.FindTemplateInstance<IAppRequestTemplate>(IAppRequestTemplate.TemplateId)
                        ?? throw new InvalidOperationException($"Template {IAppRequestTemplate.TemplateId} not found")).Namespace;

                    var rootTarget = OutputTarget;
                    while (rootTarget.Parent != null)
                    {
                        rootTarget = rootTarget.Parent;
                    }
                    var outputRoot = rootTarget.Location;

                    var rows = new List<(string Folder, string Command, string Line)>();
                    foreach (var command in ExecutionContext.MetadataManager.Services(ExecutionContext.GetApplicationConfig().Id).GetCommandModels())
                    {
                        var request = ExecutionContext.FindTemplateInstance<CommandRequestTemplate>(CommandRequestTemplate.TemplateId, command.Id)
                            ?? throw new InvalidOperationException($"Template {CommandRequestTemplate.TemplateId} not found for command {command.Name}");
                        var handler = ExecutionContext.FindTemplateInstance<CommandHandlerTemplate>(CommandHandlerTemplate.TemplateId, command.Id)
                            ?? throw new InvalidOperationException($"Template {CommandHandlerTemplate.TemplateId} not found for command {command.Name}");

                        var response = command.TypeReference.Element != null
                            ? handler.GetTypeName(command.TypeReference)
                            : "Unit";
                        var folder = Path.GetRelativePath(outputRoot, handler.GetMetadata().GetFullLocationPath())
                            .Replace('\\', '/');

                        string logging;
                        if (command.HasSerilogLogging())
                        {
                            var decorator = ExecutionContext.FindTemplateInstance<SerilogLoggingDecoratorTemplate>(SerilogLoggingDecoratorTemplate.TemplateId, command.Id)
                                ?? throw new InvalidOperationException($"Template {SerilogLoggingDecoratorTemplate.TemplateId} not found for command {command.Name}");
                            logging = $"Yes, via `{decorator.ClassName}`";
                        }
                        else
                        {
                            logging = "No";
                        }

                        rows.Add((folder, request.ClassName, $"| `{request.ClassName}` | `{handler.ClassName}` | `{response}` | `{folder}` | {logging} |"));
                    }

                    var table = new StringBuilder();
                    table.Append("| Command | Handler | Response | Folder | Serilog Logging |\n");
                    table.Append("|---|---|---|---|---|");
                    foreach (var row in rows.OrderBy(x => x.Folder, StringComparer.Ordinal).ThenBy(x => x.Command, StringComparer.Ordinal))
                    {
                        table.Append('\n').Append(row.Line);
                    }

                    file.ConfigureSection("Commands in this application", section =>
                    {
                        section.WithText(table.ToString());
                        section.WithText("If a command isn't in this table, it doesn't exist yet. Model it in the Services designer and run the Software Factory. Don't hand-write the command, the handler or its DI registration.");
                    });
                    file.ConfigureSection("Business logic goes only in `Handle`", section =>
                    {
                        section.ListItems.Single(x => x.Content.StartsWith("A command with no response type returns")).Content =
                            $"A command with no response type returns `Unit.Value` (from `{unitNamespace}`).";
                    });
                }, 0);
        }

